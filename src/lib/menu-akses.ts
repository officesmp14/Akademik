const URUT = [...MENU_PATH].sort((a, b) => b[0].length - a[0].length);

export function namaMenuDariPath(path: string): string {
  const hit = URUT.find(([prefix]) => path === prefix || path.startsWith(prefix + "/"));
  return hit ? hit[1] : path;
}
